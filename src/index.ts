const cronHandler = createCronHandler<Env>({
  name: "agent-worker",
  logger,
  handler: async (_event: ScheduledEvent, env: Env, ctx: ExecutionContext) => {
    ctx.waitUntil(
      Promise.all([
        runHousekeeping(env as unknown as HousekeepingEnv, logger).catch(
          (err) =>
            logger.error("runHousekeeping failed", { error: String(err) })
        ),
        processRoutine(env as unknown as RoutineEnv, logger, {
          getProviderManager: (e) => getProviderManager(e as unknown as Env),
          getActiveTrailingStops: (e) =>
            getActiveTrailingStops(e as unknown as Env),
        }).catch((err) =>
          logger.error("processRoutine failed", { error: String(err) })
        ),
      ])
    );
  },
});

export default {
  fetch: withRequestLog<Env>(
    async (request: Request, env: Env, ctx: ExecutionContext) => {
      const cors = corsHeaders(resolveCorsOptions(request, env));
      const corsHeadersOrEmpty =
        Object.keys(cors).length > 0 ? cors : internalCorsHeaders();
      if (request.method === "OPTIONS") {
        return new Response(null, {
          status: 204,
          headers: corsHeadersOrEmpty,
        });
      }
      const response = await router.handle(request, env, ctx);
      const wrapped = new Response(response.body, response);
      for (const [key, value] of Object.entries(corsHeadersOrEmpty)) {
        wrapped.headers.set(key, value);
      }
      return wrapped;
    },
    { service: "agent-worker", module: "router" }
  ),

  async scheduled(event: ScheduledEvent, env: Env, ctx: ExecutionContext) {
    return await cronHandler(event, env, ctx);
  },

  // Export for testing
  processRoutine: (env: Env) =>
    processRoutine(env as unknown as RoutineEnv, logger, {
      getProviderManager: (e) => getProviderManager(e as unknown as Env),
      getActiveTrailingStops: (e) =>
        getActiveTrailingStops(e as unknown as Env),
    }),
};

async function getActiveTrailingStops(env: Env): Promise<string[]> {
  try {
    const stopsList = await env.CONFIG_KV.list({ prefix: "trade:watermark:" });
    return stopsList.keys.map((k) => k.name);
  } catch (error: unknown) {
    logger.warn("Failed to list active trailing stops from KV", {
      error: toError(error),
    });
    return [];
  }
}
